/** Connection state, last-updated time, source label and stale warning. */
export function LiveStatusBar({ conn, polling, lastUpdated, stale, sourceLabel, error, onRetry }) {
  const [, setTick] = useState(0)
  useEffect(() => { const t = setInterval(() => setTick((n) => n + 1), 1000); return () => clearInterval(t) }, [])
  const ago = lastUpdated ? Math.max(0, Math.round((Date.now() - lastUpdated) / 1000)) : null
  const tone = conn === 'live' ? 'success' : conn === 'reconnecting' ? 'saffron' : 'neutral'
  const label = conn === 'live' ? 'Live' : conn === 'reconnecting' ? 'Reconnecting' : 'Offline'
  return (
    <div className="mb-4 space-y-2">
      <div className="flex flex-wrap items-center gap-x-4 gap-y-2 text-sm">
        <Badge tone={tone} dot>{label}</Badge>
        {polling && <span className="text-xs text-muted">Live socket unavailable - refreshing every 5 s</span>}
        <span className="text-muted">Last updated: <span className="font-medium text-ink">{fmtClockSec(lastUpdated)}</span>{ago != null && ` (${ago} s ago)`}</span>
        <span className="text-muted">Source: <span className="font-medium text-ink">simulated</span> <span className="text-xs">({sourceLabel})</span></span>
      </div>
      {stale && (
        <Notice tone="warning" title="Data may be stale">
          No update has arrived for over 20 seconds. The simulator may be paused or the connection interrupted; positions shown are the last known ones.
        </Notice>
      )}
      {error && (
        <Notice tone="critical" title="Could not load CleanRoute data">
          {error} {onRetry && <button type="button" onClick={onRetry} className="font-semibold underline">Try again</button>}
        </Notice>
      )}
    </div>
  )
}

